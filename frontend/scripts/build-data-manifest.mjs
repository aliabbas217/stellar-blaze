// Fingerprints the static data files the judge screens draw, and guards the scored files.
//
//   node scripts/build-data-manifest.mjs            writes data/static/MANIFEST.json, src/features/judge/manifest.generated.ts
//                                                   and the public copies in public/data/static/ (run by `prebuild`)
//   node scripts/build-data-manifest.mjs --check    writes nothing; exits 1 on any drift (files, manifest, module, copies)
//   --root <dir>                                    the frontend directory to work in (default: this script's parent)
//
// SB_REQUIRE_SCORED=1 additionally fails (exit 1) when any of the three held-out 2026 exports is missing from
// data/eval/2026/ or is not a valid 2026 export. That is how a release build refuses to ship pending tables: without
// the variable the build succeeds and the screens render their "not scored yet" state.
//
// The generated module follows the pattern of src/features/push/sw-strings.ts: committed, regenerated by prebuild, and a
// unit test (tests/unit/features/judge/manifest.test.ts) fails when it drifts.
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { checkEvalShape, checkEvaluationRecord, EVAL_FILES, EVAL_KINDS, sha256Hex } from "../src/features/judge/eval-shape.mjs";

/** What each static file is, in the vocabulary of the proof label. The origin text comes from the file itself. */
const LABELS = {
  "coast.json": "RECORDED",
  "omaa_2026_ifs_d1_wbgt_hourly.json": "RECORDED",
  "uae_ifs025_d1_wbgt_2026-09-03.json": "RECORDED",
  // Station observations 2024-2026, with commute, buffer and bedtime assumed.
  "roster_frontier.json": "REAL weather + assumed crew",
};

function parseArgs(argv) {
  const args = { check: false, root: path.join(path.dirname(fileURLToPath(import.meta.url)), "..") };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--check") args.check = true;
    else if (argv[i] === "--root") args.root = path.resolve(argv[(i += 1)] ?? "");
    else throw new Error(`unknown argument ${argv[i]}`);
  }
  return args;
}

/** The origin a file states about itself: Open-Meteo for the forecasts, Natural Earth for the coast, the script for the frontier. */
function sourceOf(file, text) {
  const parsed = JSON.parse(text);
  const origin = parsed.source ?? parsed.generated_by;
  if (typeof origin !== "string" || origin.trim() === "") {
    throw new Error(`${file}: no "source" or "generated_by" string to record as its origin`);
  }
  return origin;
}

function manifestEntries(staticDir) {
  const names = readdirSync(staticDir)
    .filter((name) => name.endsWith(".json") && name !== "MANIFEST.json")
    .sort();
  const files = {};
  for (const name of names) {
    const label = LABELS[name];
    if (label === undefined) throw new Error(`${name}: add it to LABELS in scripts/build-data-manifest.mjs (what kind of data is it?)`);
    const bytes = readFileSync(path.join(staticDir, name));
    files[`static/${name}`] = {
      sha256: sha256Hex(bytes),
      bytes: bytes.byteLength,
      source: sourceOf(name, bytes.toString("utf8")),
      label,
    };
  }
  return files;
}

function renderManifestJson(files) {
  return `${JSON.stringify({ generated_by: "scripts/build-data-manifest.mjs", files }, null, 2)}\n`;
}

function renderManifestModule(files) {
  return [
    "/*",
    " * GENERATED by scripts/build-data-manifest.mjs from data/static/*.json. Do not edit by hand.",
    " * `pnpm build` regenerates it (prebuild); tests/unit/features/judge/manifest.test.ts fails when it is stale.",
    " */",
    `export const DATA_MANIFEST = ${JSON.stringify(files, null, 2)} as const;`,
    "",
  ].join("\n");
}

/**
 * Problems with the held-out 2026 files, one line each; empty when all three are present and valid, the evaluation record is present,
 * valid and names exactly these bytes, and the published copies (what the browser recounts) are identical to them.
 */
function scoredProblems(root) {
  const problems = [];
  for (const kind of EVAL_KINDS) {
    const name = `${EVAL_FILES[kind].name}.json`;
    const file = path.join(root, "data", "eval", "2026", name);
    if (!existsSync(file)) {
      problems.push(`data/eval/2026/${name} is missing`);
      continue;
    }
    let parsed;
    try {
      parsed = JSON.parse(readFileSync(file, "utf8"));
    } catch {
      problems.push(`data/eval/2026/${name} is not valid JSON`);
      continue;
    }
    const problem = checkEvalShape(kind, parsed, "scored_2026");
    if (problem !== null) problems.push(`data/eval/2026/${name}: ${problem}`);
  }
  problems.push(...recordProblems(root));
  return problems;
}

/** The evaluation record (the lock the run started under) must be there, valid, and describe exactly the files that ship. */
function recordProblems(root) {
  const dir = path.join(root, "data", "eval", "2026");
  const recordFile = path.join(dir, "evaluation_record.json");
  if (!existsSync(recordFile)) return ["data/eval/2026/evaluation_record.json is missing (scripts/sync-eval-data.mjs --git writes it)"];
  let record;
  try {
    record = JSON.parse(readFileSync(recordFile, "utf8"));
  } catch {
    return ["data/eval/2026/evaluation_record.json is not valid JSON"];
  }
  const problem = checkEvaluationRecord(record);
  if (problem !== null) return [`data/eval/2026/evaluation_record.json: ${problem}`];
  const problems = [];
  for (const kind of EVAL_KINDS) {
    const name = `${EVAL_FILES[kind].name}.json`;
    const file = path.join(dir, name);
    if (!existsSync(file)) continue;
    const bytes = readFileSync(file);
    if (record.files[name]?.sha256 !== sha256Hex(bytes)) problems.push(`data/eval/2026/${name} is not the file the evaluation record names (its SHA-256 differs)`);
  }
  for (const name of [...EVAL_KINDS.map((kind) => `${EVAL_FILES[kind].name}.json`), "evaluation_record.json"]) {
    const copy = path.join(root, "public", "data", "eval", "2026", name);
    const source = path.join(dir, name);
    if (existsSync(source) && (!existsSync(copy) || !readFileSync(copy).equals(readFileSync(source)))) problems.push(`public/data/eval/2026/${name} is missing or differs from data/eval/2026/${name}`);
  }
  return problems;
}

function main() {
  const { check, root } = parseArgs(process.argv.slice(2));
  const staticDir = path.join(root, "data", "static");
  const publicDir = path.join(root, "public", "data", "static");
  const manifestPath = path.join(staticDir, "MANIFEST.json");
  const modulePath = path.join(root, "src", "features", "judge", "manifest.generated.ts");

  const files = manifestEntries(staticDir);
  const wantedJson = renderManifestJson(files);
  const wantedModule = renderManifestModule(files);
  const errors = [];

  if (check) {
    const read = (file) => (existsSync(file) ? readFileSync(file, "utf8") : null);
    if (read(manifestPath) !== wantedJson) errors.push("data/static/MANIFEST.json does not match the files in data/static (a file changed, was added or removed)");
    if (read(modulePath) !== wantedModule) errors.push("src/features/judge/manifest.generated.ts does not match the files in data/static");
    for (const name of Object.keys(files).map((key) => key.replace("static/", ""))) {
      const copy = path.join(publicDir, name);
      if (!existsSync(copy) || !readFileSync(copy).equals(readFileSync(path.join(staticDir, name)))) {
        errors.push(`public/data/static/${name} is missing or differs from data/static/${name}`);
      }
    }
    if (existsSync(publicDir)) {
      const extra = readdirSync(publicDir).filter((name) => name.endsWith(".json") && !(`static/${name}` in files));
      for (const name of extra) errors.push(`public/data/static/${name} has no source in data/static`);
    }
  } else {
    writeFileSync(manifestPath, wantedJson);
    mkdirSync(path.dirname(modulePath), { recursive: true });
    writeFileSync(modulePath, wantedModule);
    mkdirSync(publicDir, { recursive: true });
    for (const key of Object.keys(files)) {
      const name = key.replace("static/", "");
      copyFileSync(path.join(staticDir, name), path.join(publicDir, name));
    }
  }

  if (process.env.SB_REQUIRE_SCORED === "1") {
    for (const problem of scoredProblems(root)) errors.push(`SB_REQUIRE_SCORED=1: ${problem}`);
  }

  if (errors.length > 0) {
    for (const error of errors) console.error(error);
    if (check) console.error("Run `node scripts/build-data-manifest.mjs` to regenerate, and commit the result.");
    process.exit(1);
  }
  console.log(`${check ? "checked" : "wrote"} ${String(Object.keys(files).length)} static data files`);
}

main();
