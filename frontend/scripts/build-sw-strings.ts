// Generates src/features/push/sw-strings.ts from the `push` namespace of messages/*.json: the words the service
// worker shows in a notification, for every locale, bundled into the worker (it has no next-intl and no network
// when a push arrives). Run by `prebuild`; the output is committed, and tests/unit/features/push/sw-strings.test.ts
// fails when the committed file differs from what the messages produce.
// Node strips the types of this file: no "@/" imports, no enums, relative imports end in ".ts".
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export interface PushStrings {
  /** The app's name: the title of the neutral notification shown for a push that carries nothing the worker can read. */
  appName: string;
  title: { site: string; crew: string };
  body: string;
  level: Record<"green" | "amber" | "orange" | "red", string>;
}

/** Every `{name}` of a message. The worker substitutes `{level}` and nothing else: it is not an ICU formatter. */
function placeholdersOf(message: string): string[] {
  return [...message.matchAll(/\{[^}]*\}/g)].map((match) => match[0]);
}

function asRecord(value: unknown, where: string): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) throw new Error(`${where} is not an object`);
  return value as Record<string, unknown>;
}

function asString(value: unknown, where: string, allowed: readonly string[]): string {
  if (typeof value !== "string" || value.trim() === "") throw new Error(`${where} is not a non-empty string`);
  const found = placeholdersOf(value);
  const unknown = found.filter((placeholder) => !allowed.includes(placeholder));
  if (unknown.length > 0) {
    throw new Error(`${where} uses ${unknown.join(" ")}; the service worker only fills ${allowed.join(" ") || "no placeholder"} here`);
  }
  return value;
}

/**
 * The `push` namespace of one locale's messages plus `common.appName`, checked: a missing key or a placeholder the
 * worker cannot fill throws.
 */
export function pushStringsOf(messages: unknown, locale: string): PushStrings {
  const root = asRecord(messages, `${locale}.json`);
  const push = asRecord(root["push"], `${locale}.json push`);
  const common = asRecord(root["common"], `${locale}.json common`);
  const title = asRecord(push["title"], `${locale}.json push.title`);
  const level = asRecord(push["level"], `${locale}.json push.level`);
  const where = (key: string) => `${locale}.json push.${key}`;
  return {
    appName: asString(common["appName"], `${locale}.json common.appName`, []),
    title: {
      site: asString(title["site"], where("title.site"), ["{level}"]),
      crew: asString(title["crew"], where("title.crew"), ["{level}"]),
    },
    body: asString(push["body"], where("body"), []),
    level: {
      green: asString(level["green"], where("level.green"), []),
      amber: asString(level["amber"], where("level.amber"), []),
      orange: asString(level["orange"], where("level.orange"), []),
      red: asString(level["red"], where("level.red"), []),
    },
  };
}

/**
 * The text of src/features/push/sw-strings.ts for these messages (locale code -> parsed messages file). Pure and
 * deterministic: locales in code order, JSON formatting, one trailing newline and no trailing whitespace, so the
 * pre-commit fixers leave the committed file as it is.
 */
export function renderSwStrings(messagesByLocale: Readonly<Record<string, unknown>>): string {
  const strings: Record<string, PushStrings> = {};
  for (const locale of Object.keys(messagesByLocale).sort()) {
    strings[locale] = pushStringsOf(messagesByLocale[locale], locale);
  }
  return [
    "/*",
    " * GENERATED by scripts/build-sw-strings.ts from the `push` namespace of messages/*.json. Do not edit by hand.",
    " * `pnpm build` regenerates it (prebuild); tests/unit/features/push/sw-strings.test.ts fails when it is stale.",
    " * The service worker bundles it: it has no next-intl and may have no network when a push arrives.",
    " */",
    `export const SW_STRINGS = ${JSON.stringify(strings, null, 2)} as const;`,
    "",
  ].join("\n");
}

const root = path.resolve(import.meta.dirname, "..");
export const MESSAGES_DIR = path.join(root, "messages");
export const SW_STRINGS_FILE = path.join(root, "src", "features", "push", "sw-strings.ts");

/** Reads every messages/<locale>.json. */
export function readAllMessages(dir: string = MESSAGES_DIR): Record<string, unknown> {
  const byLocale: Record<string, unknown> = {};
  for (const file of readdirSync(dir).filter((name) => name.endsWith(".json"))) {
    byLocale[path.basename(file, ".json")] = JSON.parse(readFileSync(path.join(dir, file), "utf8"));
  }
  return byLocale;
}

if (import.meta.main) {
  writeFileSync(SW_STRINGS_FILE, renderSwStrings(readAllMessages()));
  console.log(`wrote ${path.relative(root, SW_STRINGS_FILE)}`);
}
